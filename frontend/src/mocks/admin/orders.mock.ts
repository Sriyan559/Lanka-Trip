export function getMockOrderDetail(orderIdOrRef: string): OrderDetail | null {
  const decoded = decodeURIComponent(orderIdOrRef).trim();
  
  if (decoded === "ORD-2026-009021" || decoded === "5S6814-409-52H" || decoded === "9021" || decoded === "ORD-2026-501") {
    return primaryMockOrderDetail;
  }

  const baseOrder = mockMarketplaceOrders.find(
    (o) =>
      o.orderReference === decoded ||
      o.id === decoded ||
      o.dbOrderId === decoded ||
      o.orderReference.toLowerCase() === decoded.toLowerCase() ||
      o.id.toLowerCase() === decoded.toLowerCase()
  );

  if (!baseOrder) return null;

  return {
    ...primaryMockOrderDetail,
    id: baseOrder.id,
    orderReference: baseOrder.orderReference,
    dbOrderId: baseOrder.dbOrderId,
    orderDateTime: baseOrder.orderDateTime,
    createdAt: baseOrder.orderDateTime,
    customerReference: `CUS-2026-0${Math.floor(1000 + Math.random() * 9000)}`,
    customer: {
      ...primaryMockOrderDetail.customer,
      name: baseOrder.customerName,
      email: baseOrder.customerEmail || `${baseOrder.customerName.toLowerCase().replace(/\s+/g, ".")}@example.com`,
      phone: baseOrder.customerPhone || "+94 77 999 8888",
    },
    paymentStatus: baseOrder.paymentStatus,
    orderStatus: baseOrder.orderStatus,
    fulfilmentStatus: baseOrder.fulfilmentStatus,
    deliveryStatus: baseOrder.deliveryStatus,
    riskLevel: baseOrder.riskLevel,
    slaStatus: baseOrder.slaStatus,
    itemsCount: baseOrder.itemsCount,
    suppliersCount: baseOrder.suppliersCount,
    splitOrder: baseOrder.splitOrder,
    assignedOfficer: baseOrder.assignedOfficer,
    financials: {
      ...primaryMockOrderDetail.financials,
      orderTotal: baseOrder.orderTotal,
      subtotal: baseOrder.orderTotal * 0.92,
      tax: baseOrder.orderTotal * 0.07,
      paid: baseOrder.paymentStatus === "Paid" ? baseOrder.orderTotal : 0,
      platformCommission: baseOrder.orderTotal * 0.1,
      supplierPayable: baseOrder.orderTotal * 0.85,
      captured: baseOrder.paymentStatus === "Paid" ? baseOrder.orderTotal : 0,
    },
  };
}
